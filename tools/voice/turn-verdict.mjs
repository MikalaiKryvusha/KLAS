// tools/voice/turn-verdict.mjs — вердикт «состоялся ли ход ядра» (охранник bugs/12).
//
// Почему ОТДЕЛЬНЫЙ модуль, а не функция внутри voice-bench.mjs: бенч — исполняемый скрипт, он
// запускает прогон прямо в теле. Любой импорт из него ради одной чистой функции ЗАПУСКАЕТ весь бенч
// (поймано на себе 2026-07-29: попытка проверить охранник подняла целый прогон и уронила гейтвей).
// Проверяемая логика обязана жить там, откуда её можно импортировать без побочных эффектов.
//
// [TESTED: 2026-07-29 · фикстура T0d в voice-bench — 8/8; та же фикстура против СТАРОЙ логики
//  (чёрный список без finish_reason) даёт 5/8, то есть охранник краснеет ровно на трёх классах,
//  ради которых поставлен]

// Строки-ЗАГЛУШКИ ядра: формально ответ, фактически провал хода (bugs/12).
// Встретил новую форму отказа — добавляй сюда строкой.
export const CORE_STUB_REPLIES = [
  /^no response from openclaw\.?$/i,
  /^\(?no (reply|answer|response)\)?\.?$/i,
  /^error[:\s]/i,
  /^ЯДРО ответило HTTP/i,
];

// ОСТАТКИ МАШИННОЙ РАЗМЕТКИ в ответе, который идёт человеку В УШИ (класс bugs/14).
// T0c гарантирует, что ИЗВЕСТНАЯ форма `[[tts(...)]]` снимается; здесь ловится НЕИЗВЕСТНАЯ — новая
// директива, недорезанный тул-колл, JSON. Ни одна из этих последовательностей не встречается в живой
// русской речи, поэтому ложных тревог они не дают.
export const CORE_MARKUP_LEAK = [/\[\[|\]\]/, /<\/?tool_call>/i, /<\|[a-z_]+\|>/i, /^\s*[{[]"/];

/**
 * Вердикт по ходу ядра — БЕЛЫЙ список поверх чёрного (записанный следующий шаг bugs/12).
 *
 * Почему белый нужен: чёрный список ловит только ИЗВЕСТНЫЕ формы отказа, а бенч существует ровно
 * ради неизвестных. Ход считается состоявшимся, только если ядро само сказало, что закончило штатно:
 * `finish_reason: "stop"` из финального чанка SSE. Наблюдение 2026-07-29: гейтвей его шлёт, но с
 * ПУСТОЙ дельтой — поэтому прежняя проверка на контент в `pipeline.mjs` его молча выбрасывала.
 *
 * Почему чёрный НЕ убран: `stop` означает «модель договорила», а не «сказала осмысленное» — заглушка
 * «No response from OpenClaw.» приезжает именно со `stop`. Два фильтра ловят РАЗНЫЕ классы:
 * белый — оборванные и незавершённые ходы, чёрный — завершённые, но пустые по сути.
 *
 * `finishReason === null` — это НЕ «всё хорошо»: значит ядро не сообщило причину вовсе. Такой ход
 * помечается провалившимся с явной формулировкой, а не молча засчитывается: bugs/12 случился ровно
 * из-за того, что отсутствие сигнала читалось как успех.
 *
 * @param {{reply?: string, rawReply?: string, finishReason?: string|null}} r результат runTurn
 * @returns {{ok: boolean, why: string}}
 */
export function coreTurnVerdict(r) {
  const raw = (r?.rawReply ?? r?.reply ?? '').trim();
  if (!r?.reply) return { ok: false, why: 'пустой ответ ядра' };
  if (r.finishReason == null) return { ok: false, why: 'ядро НЕ сообщило finish_reason — ход не подтверждён' };
  if (r.finishReason !== 'stop') return { ok: false, why: `ход ОБОРВАН: finish_reason=${r.finishReason}` };
  const stub = CORE_STUB_REPLIES.find((re) => re.test(raw));
  if (stub) return { ok: false, why: `ЯДРО НЕ ОТВЕТИЛО — заглушка вместо ответа: «${raw.slice(0, 60)}»` };
  const leak = CORE_MARKUP_LEAK.find((re) => re.test(raw));
  if (leak) return { ok: false, why: `В ОТВЕТЕ ЯДРА МАШИННАЯ РАЗМЕТКА (${leak}): «${raw.slice(0, 60)}» — в звук она не попадёт (снимается), но это дефект ядра, а не норма` };
  return { ok: true, why: `${r.reply.length} симв., finish_reason=stop` };
}

