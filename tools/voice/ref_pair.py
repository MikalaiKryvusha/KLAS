# -*- coding: utf-8 -*-
"""
Охранник ПАРЫ «эталонный звук ↔ эталонный текст» для клонирования голоса (`bugs/16`).

Зачем существует
----------------
Клон голоса строится не по звуку, а по ПАРЕ: модель смотрит, сколько текста уложено в сколько
звука, и по этой пропорции говорит дальше. Рассогласуй пару — и ломается ВСЁ сразу:

  * F5/ESpeech режет эталонный ЗВУК до 12 000 мс (`f5_tts/infer/utils_infer.py:344`),
    а ТЕКСТ эталона не трогает вовсе. Пара молча расходится, ошибки нет;
  * модель считает, что в звуке лежит весь текст, и говорит наш текст ВДВОЕ быстрее;
  * лишний текст эталона она договаривает ВСЛУХ внутри нашего синтеза — ассистент произносит
    то, чего ему не поручали.

[TESTED: 2026-07-29 · замер `bugs/16`, один и тот же эталонный звук 9.27 с, три варианта.
Пара согласована (133 символа текста) → 5 из 5 синтезов чистые, «Добрый вечер, Николай.
Система KLAS в порядке, я к вашим услугам». Пара рассогласована (272 символа на тот же звук)
→ 10 из 10 испорчены, в расшифровках дословно всплывают слова эталона: «Пересели в добрый
вечер…», «И скрылись. Добрый вечер…». Длительность синтеза при этом падает вдвое
(15.87 с → 7.87 с на одном и том же тексте).]

Почему проверка ПО СИМВОЛАМ, а не по «правильности» текста
----------------------------------------------------------
Нам не нужно знать, верна ли расшифровка эталона: нужно знать, соответствует ли ЕЁ ОБЪЁМ
длительности звука. Это чистая арифметика — ровно тот случай, когда прокси и есть предмет
(EXP-0030: герцами голос не меряют, а вот символы на секунду меряют именно то, что названо).

Использование
-------------
    from ref_pair import check_ref_pair
    check_ref_pair(REF_WAV, REF_TXT)          # бросит ValueError с объяснением
    check_ref_pair(REF_WAV, REF_TXT, engine="f5")   # + проверка порога обрезки F5
"""
import wave
import contextlib

# Порог обрезки эталона у F5/ESpeech — прочитан в исходнике, не выдуман:
# f5_tts/infer/utils_infer.py:344 → `if len(aseg) > 12000: aseg = aseg[:12000]`
F5_REF_CLIP_MS = 12_000

# Коридор темпа русской дикторской начитки, символов в секунду.
# Замерен на нашем же материале: эталон Вихрова 9.27 с несёт 133 символа = 14.3 симв/с;
# рассогласованная пара давала 29.3 симв/с и ломала синтез. Границы взяты с запасом,
# чтобы охранник ловил РАССИНХРОН, а не придирался к манере чтения.
CPS_MIN, CPS_MAX = 8.0, 22.0


def wav_duration_s(path: str) -> float:
    """Длительность wav в секундах. Без зависимостей — только stdlib."""
    with contextlib.closing(wave.open(path, "rb")) as w:
        return w.getnframes() / float(w.getframerate())


def check_ref_pair(ref_wav: str, ref_text: str, engine: str = "f5") -> dict:
    """
    Проверяет, что эталонный текст соответствует эталонному звуку по объёму.

    Возвращает словарь замера. Бросает ValueError, если пара непригодна — намеренно
    ЖЁСТКО: молчаливое предупреждение здесь бесполезно, потому что дефект тоже молчаливый
    (синтез отработает, вернёт wav, и никакой ошибки не будет — просто ассистент скажет
    не то). Дефект без исключения = дефект, который дойдёт до ушей человека.
    """
    dur = wav_duration_s(ref_wav)
    text = (ref_text or "").strip()
    n = len(text)
    if n == 0:
        raise ValueError(
            f"Эталонный текст пуст. Для F5 это ДОПУСТИМО (он расшифрует звук сам через whisper), "
            f"но у нас whisper не установлен — передай текст явно: {ref_wav}"
        )
    cps = n / dur if dur > 0 else float("inf")

    if engine == "f5" and dur * 1000 > F5_REF_CLIP_MS:
        raise ValueError(
            f"Эталон {ref_wav} длиной {dur:.2f} с — F5/ESpeech обрежет ЗВУК до "
            f"{F5_REF_CLIP_MS/1000:.0f} с, а ТЕКСТ ({n} символов) оставит целиком. "
            f"Пара разойдётся молча (bugs/16). Нарежь эталон ≤{F5_REF_CLIP_MS/1000:.0f} с "
            f"и подай РОВНО его текст."
        )

    if not (CPS_MIN <= cps <= CPS_MAX):
        raise ValueError(
            f"Пара «звук ↔ текст» не сходится: {n} символов на {dur:.2f} с = {cps:.1f} симв/с "
            f"(норма {CPS_MIN}–{CPS_MAX}). Обычная причина — текст от ДРУГОГО куска записи. "
            f"Файл: {ref_wav}"
        )

    return {"ref_audio_s": round(dur, 2), "ref_chars": n, "cps": round(cps, 1)}


if __name__ == "__main__":
    # Самопроверка: гоняется без аргументов, красная на сломанной логике.
    # Фикстуры — ЧИСЛА, а не файлы: проверяется арифметика решения, а не наличие wav.
    def _fake(dur, n, engine="f5"):
        class _P:
            pass
        # подменяем измерение длительности, чтобы не заводить wav-фикстуры ради арифметики
        global wav_duration_s
        orig = wav_duration_s
        wav_duration_s = lambda _p: dur
        try:
            return check_ref_pair("фикстура.wav", "x" * n, engine=engine)
        finally:
            wav_duration_s = orig

    ok = True

    # 1. Наша реальная согласованная пара — должна пройти.
    try:
        r = _fake(9.27, 133)
        print(f"PASS  согласованная пара: {r}")
    except ValueError as e:
        ok = False
        print(f"FAIL  согласованная пара отвергнута: {e}")

    # 2. Ровно тот случай, что сломал синтез в замере: тот же звук, вдвое больше текста.
    try:
        _fake(9.27, 272)
        ok = False
        print("FAIL  рассогласованная пара (272 симв на 9.27 с) ПРОПУЩЕНА")
    except ValueError:
        print("PASS  рассогласованная пара отвергнута")

    # 3. Эталон длиннее порога обрезки F5 — отвергается ДО синтеза.
    try:
        _fake(15.0, 215)
        ok = False
        print("FAIL  эталон 15 с ПРОПУЩЕН — F5 обрежет его молча")
    except ValueError:
        print("PASS  эталон длиннее 12 с отвергнут")

    # 4. Тот же эталон 15 с для движка без обрезки (Qwen) — проходить ДОЛЖЕН.
    try:
        r = _fake(15.0, 215, engine="qwen")
        print(f"PASS  15 с допустимы для движка без обрезки: {r}")
    except ValueError as e:
        ok = False
        print(f"FAIL  движок без обрезки зря отвергнут: {e}")

    print("=== ИТОГ:", "PASS" if ok else "FAIL", "===")
    raise SystemExit(0 if ok else 1)
