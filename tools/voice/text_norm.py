"""
Слой нормализации речи KLAS — общий для ЛЮБОГО движка синтеза.

Зачем отдельным модулем. Слой родился внутри `silero_daemon.py` (bugs/13: Silero молча ГЛОТАЛ
цифры), но он движку не принадлежит: espeak-ng у Piper и Qwen3-TTS одинаково не разворачивают
НАШИ сокращения — «11.4 ГБ» звучит как «одиннадцать четыре гб», «115 КБ/с» как «кб слэш с».
Владелец 2026-07-29, слушая макет Qwen: «единицы измерения плохо читает. Код тоже».
Значит слой переживает смену движка и обязан жить отдельно от него.

Импортировать модулем, а не из исполняемого скрипта: импорт `silero_daemon` запустил бы демона
целиком (EXP-0028).

Порядок применения важен и не произволен:
  1) markdown вон           — разметка не звучит
  2) код в слова            — ДО единиц: в коде есть «-m», «/», «=», которые единицы поняли бы неверно
  3) единицы в слова        — пока числа ещё ЦИФРАМИ (правила смотрят на цифру слева)
  4) дроби и числа в слова  — последним, иначе развернутые слова снова не с чем сопоставить

[NOT-TESTED] — маркер снимается после прогона на фикстуре и прослушивания.
"""
import re

# ---------------------------------------------------------------- числа
_ONES_M = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_ONES_F = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
         "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот"]


def _plural(n: int, forms):
    """forms = (1, 2-4, 5-0). Русская морфология числительных."""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def _under_1000(n: int, feminine: bool):
    out = []
    if n >= 100:
        out.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(_TEENS[n - 10])
        return out
    if n >= 20:
        out.append(_TENS[n // 10])
        n %= 10
    if n:
        out.append((_ONES_F if feminine else _ONES_M)[n])
    return out


def number_to_ru_words(num: int) -> str:
    if num == 0:
        return "ноль"
    parts = []
    if num < 0:
        parts.append("минус")
        num = -num
    for scale, (forms, fem) in (
        (10 ** 9, (("миллиард", "миллиарда", "миллиардов"), False)),
        (10 ** 6, (("миллион", "миллиона", "миллионов"), False)),
        (10 ** 3, (("тысяча", "тысячи", "тысяч"), True)),
    ):
        if num >= scale:
            chunk = num // scale
            parts += _under_1000(chunk, fem) + [_plural(chunk, forms)]
            num %= scale
    if num:
        parts += _under_1000(num, False)
    return " ".join(p for p in parts if p)


# Дробные: «11.4» и «11,4». Раньше их резало на два целых («одиннадцать четыре») —
# именно это владелец услышал в макете Qwen. Дробную часть читаем разрядом.
_FRACTION_NAMES = {1: ("десятая", "десятых"), 2: ("сотая", "сотых"), 3: ("тысячная", "тысячных")}


def _decimal_to_words(m) -> str:
    whole, frac = m.group(1), m.group(2)
    w = int(whole)
    f = int(frac)
    digits = len(frac)
    whole_words = " ".join(_under_1000(w, True)) if w else "ноль"
    whole_tail = _plural(w, ("целая", "целых", "целых"))
    if digits in _FRACTION_NAMES:
        one, many = _FRACTION_NAMES[digits]
        frac_tail = _plural(f, (one, many, many))
    else:                                    # разряд глубже тысячных не называем — читаем цифрами
        return f"{whole_words} {whole_tail} " + " ".join(_ONES_M[int(d)] or "ноль" for d in frac)
    frac_words = " ".join(_under_1000(f, True)) if f else "ноль"
    return f"{whole_words} {whole_tail} {frac_words} {frac_tail}"


_DECIMAL = re.compile(r"\b(\d+)[.,](\d+)\b")


def digits_to_words(text: str) -> str:
    """Дроби разворачиваем ПЕРВЫМИ, иначе целочисленное правило разрежет их пополам."""
    text = _DECIMAL.sub(_decimal_to_words, text)
    return re.sub(r"-?\d+", lambda m: number_to_ru_words(int(m.group())), text)


# ---------------------------------------------------------------- единицы
# Разворачиваем только то, что стоит ПОСЛЕ ЧИСЛА, — иначе «в» из «м/в» поедет на обычном тексте.
_UNIT_WORDS = [
    (r"°\s*C|℃|(?<=\d)\s*C\b", " градусов Цельсия"),
    (r"°\s*F|℉", " градусов Фаренгейта"),
    (r"%", " процентов"),
    (r"\bкб/с\b|\bКБ/с\b|\bkb/s\b", " килобайт в секунду"),
    (r"\bмб/с\b|\bМБ/с\b|\bmb/s\b", " мегабайт в секунду"),
    (r"\bгб/с\b|\bГБ/с\b|\bgb/s\b", " гигабайт в секунду"),
    (r"\bкм/ч\b", " километров в час"),
    (r"\bм/с\b", " метров в секунду"),
    (r"\bкб\b|\bКБ\b", " килобайт"),
    (r"\bмб\b|\bМБ\b", " мегабайт"),
    (r"\bгб\b|\bГБ\b", " гигабайт"),
    (r"\bтб\b|\bТБ\b", " терабайт"),
    (r"\bкм\b", " километров"),
    (r"\bсм\b", " сантиметров"),
    (r"\bмм\b", " миллиметров"),
    (r"\bкг\b", " килограммов"),
    (r"\bч\.", " часов"),
    (r"\bмин\b", " минут"),
    (r"\bсек\b", " секунд"),
    (r"\bт\.е\.", "то есть"),
    (r"\bт\.д\.", "так далее"),
    (r"\bт\.п\.", "тому подобное"),
]
_HAS_NUMBER_BEFORE = re.compile(r"\d\s*$")


def expand_units(text: str) -> str:
    for pattern, word in _UNIT_WORDS:
        def repl(m, word=word):
            before = text[:m.start()]
            return word if _HAS_NUMBER_BEFORE.search(before) or "." in m.group() or "%" in m.group() else m.group()
        text = re.sub(pattern, repl, text)
    return re.sub(r"\s{2,}", " ", text)


# ---------------------------------------------------------------- код
# Жалоба владельца «Код тоже». Цель НЕ в том, чтобы код можно было восстановить на слух, —
# цель в том, чтобы он ЗВУЧАЛ КАК РЕЧЬ, а не как набор символов. Поэтому разворачиваем
# математику и операторы, а кавычки просто снимаем: их содержимое произносится как текст.
_CODE_RULES = [
    (r"\bf\s*\(\s*x\s*\)", "эф от икс"),                 # частая форма записи функции
    (r"(?<=\s)-([a-zA-Z])\b", r"ключ \1"),               # флаг вида -m
    (r"--([a-zA-Z-]+)", r"ключ \1"),                     # длинный флаг
    (r"\s*==\s*", " равно равно "),
    (r"\s*=\s*", " равно "),
    (r"\s*\+\s*", " плюс "),
    (r"(?<=\d)\s*\*\s*(?=\d)", " умножить на "),
    (r"(?<=\d)\s*/\s*(?=\d)", " делить на "),
    (r"\s*->\s*", " стрелка "),
    (r"\s*=>\s*", " стрелка "),
    (r"[\"«»']", " "),                                    # кавычки не звучат — содержимое остаётся
    (r"\s*\|\s*", " вертикальная черта "),
    (r"\s*&&\s*", " и "),
]
# «2x» → «два икс»: без пробела синтез читает это одним комком
_IMPLICIT_MUL = re.compile(r"(?<=\d)(?=[a-zA-Zа-яА-Я])")


def expand_code(text: str) -> str:
    for pattern, repl in _CODE_RULES:
        text = re.sub(pattern, repl, text)
    text = _IMPLICIT_MUL.sub(" ", text)
    return re.sub(r"\s{2,}", " ", text)


# ---------------------------------------------------------------- латиница в речи
# Решение владельца (канон, 2026-07-29): английское произносится ТРАНСЛИТЕРАЦИЕЙ КИРИЛЛИЦЕЙ —
# «второй способ самый хороший». Отслушивание клонов 2026-07-30 показало, ГДЕ это применять:
#
#   ESpeech (4000 ч РУССКОГО, английских фонем в модели нет) — «английские слова произносит плохо»,
#       «RTX 5070 Ti произносит плохо», «тараторит на коде и английских командах». Ему латиница
#       не по силам в принципе ⇒ транслитерация ОБЯЗАТЕЛЬНА.
#   Qwen3-TTS (мультиязычный) — «сильно лучше произносит английские слова… есть немного акцента
#       на англоицизмах». У него английский УЖЕ лучшая часть, а транслитерация акцент как раз и
#       создаёт ⇒ полную транслитерацию ему НЕ применяем.
#
# Отсюда три режима, а не один флаг «вкл/выкл»:
#   'off'     — латиница как есть (для отладки и сравнения)
#   'abbrev'  — только СОКРАЩЕНИЯ и словарь имён (нужно ОБОИМ движкам: «RTX» по-русски читается
#               буквами «Эр-Ти-Икс» в любом случае, это не акцент, а верное чтение аббревиатуры)
#   'full'    — 'abbrev' + транслитерация обычных английских слов (для ESpeech)
#
# ⚠️ Честная граница: правильный путь — англоязычный G2P (espeak-ng), как записано в каноне.
# Ни `espeak-ng`, ни `phonemizer` в окружении нет, установка идёт через рвущийся VPN-туннель.
# Здесь — правиловая транслитерация + СЛОВАРЬ ПРОИЗНОШЕНИЯ. Словарь — не подгонка под тест, а
# штатная практика синтеза речи (lexicon/exception dictionary): у любого движка есть список слов,
# которые правила читают неверно. Но словарь ОБЯЗАН расти по мере находок, а правила остаются
# грубыми — это первая версия, а не финал.

# Русские названия латинских букв — для аббревиатур, читаемых по буквам.
_LATIN_LETTER_NAMES = {
    "a": "эй", "b": "би", "c": "си", "d": "ди", "e": "и", "f": "эф", "g": "джи", "h": "эйч",
    "i": "ай", "j": "джей", "k": "кей", "l": "эль", "m": "эм", "n": "эн", "o": "оу", "p": "пи",
    "q": "кью", "r": "ар", "s": "эс", "t": "ти", "u": "ю", "v": "ви", "w": "дабл-ю",
    "x": "икс", "y": "уай", "z": "зед",
}

# Словарь произношения. РАЗДЕЛЁН НА ДВА, и это разделение поймала самопроверка: сначала я свалил
# в один словарь и имена, и обычные английские слова — и режим 'abbrev', обещавший «слова Qwen не
# трогаем», молча транслитерировал «machine learning». Тест на обратную сторону покраснел.
#
# _NAMES — применяются ВСЕГДА, обоим движкам. Это токены, которые НИ ОДИН движок не читает верно:
# аббревиатуры с нестандартным чтением, имена с точками внутри, непроизносимые акронимы.
_NAMES = {
    "rtx": "Эр-Ти-Икс",
    "ti": "Ти",                       # суффикс видеокарты, а не «тай»
    "gb": "гигабайт",
    "qwen": "Квен",                   # китайское имя, английский G2P даёт «квен» наугад
    "llama.cpp": "лама си-плюс-плюс",
    "model.onnx": "модел точка оннх",  # имя файла с точкой внутри ломает любой TTS
    "onnx": "оннх",
    "npm": "эн-пи-эм",                # строчная аббревиатура — правило _is_abbrev её не видит
    "webui": "веб-ю-ай",
    "kiwix": "кивикс",
    "klas": "КЛАС",                   # ЗАглавные 4 буквы: без этой строки прочлось бы по буквам
    "jarvis": "Джарвис",
    "joi": "Джой",
}
# _WORDS — обычные английские слова. Только в режиме 'full' (ESpeech). Для Qwen они остаются
# английскими намеренно: владелец назвал его английский «сильно лучше», и портить его не за что.
_WORDS = {
    "llama": "лама",
    "open": "оупен",
    "python": "пайтон",
    "git": "гит",
    "commit": "коммит",
    "build": "билд",
    "run": "ран",
    "fix": "фикс",
    "voice": "войс",
    "machine": "мащин",
    "learning": "лёрнинг",
    "script": "скрипт",
}

# Правиловая транслитерация: диграфы ПЕРЕД одиночными буквами, иначе «sh» станет «сх».
_TRANSLIT_RULES = [
    ("tion", "шн"), ("igh", "ай"), ("ough", "аф"),
    ("ch", "ч"), ("sh", "ш"), ("th", "т"), ("ph", "ф"), ("ck", "к"), ("qu", "кв"),
    ("ee", "и"), ("ea", "и"), ("oo", "у"), ("ou", "ау"), ("ow", "оу"),
    ("ai", "эй"), ("ay", "эй"), ("ey", "эй"), ("oa", "оу"), ("ie", "и"),
    ("a", "а"), ("b", "б"), ("c", "к"), ("d", "д"), ("e", "е"), ("f", "ф"), ("g", "г"),
    ("h", "х"), ("i", "и"), ("j", "дж"), ("k", "к"), ("l", "л"), ("m", "м"), ("n", "н"),
    ("o", "о"), ("p", "п"), ("q", "к"), ("r", "р"), ("s", "с"), ("t", "т"), ("u", "а"),
    ("v", "в"), ("w", "в"), ("x", "кс"), ("y", "й"), ("z", "з"),
]

_LATIN_TOKEN = re.compile(r"[A-Za-z][A-Za-z.+#]*")


def _spell_out(token: str) -> str:
    """Аббревиатуру читаем по буквам русскими названиями: RTX → Эр-Ти-Икс."""
    return "-".join(_LATIN_LETTER_NAMES.get(c.lower(), c).capitalize() for c in token if c.isalpha())


def _translit_word(token: str) -> str:
    low = token.lower()
    out = []
    i = 0
    while i < len(low):
        for src, dst in _TRANSLIT_RULES:
            if low.startswith(src, i):
                out.append(dst)
                i += len(src)
                break
        else:
            out.append(low[i])       # точка, плюс, решётка — оставляем как есть
            i += 1
    return "".join(out)


def _is_abbrev(token: str) -> bool:
    """Аббревиатура: 2–4 буквы, все заглавные, и это не слово из словаря."""
    letters = [c for c in token if c.isalpha()]
    return 2 <= len(letters) <= 4 and all(c.isupper() for c in letters)


def latin_to_cyrillic(text: str, mode: str = "abbrev") -> str:
    if mode == "off":
        return text

    def repl(m):
        token = m.group().rstrip(".")
        trailing = m.group()[len(token):]
        low = token.lower()
        if low in _NAMES:
            return _NAMES[low] + trailing
        # Одиночная латинская буква — это переменная или флаг («2x», «ключ m»), а не английское
        # слово. По-русски она читается НАЗВАНИЕМ буквы: x → икс, m → эм. Верно в ЛЮБОМ режиме,
        # поэтому стоит до проверки на mode. (Поймано самопроверкой: было «два кс при кс».)
        if len(low) == 1 and low.isalpha():
            return _LATIN_LETTER_NAMES[low] + trailing
        if _is_abbrev(token):
            return _spell_out(token) + trailing
        if mode == "full":
            return _WORDS.get(low, _translit_word(token)) + trailing
        return m.group()

    return _LATIN_TOKEN.sub(repl, text)


# ---------------------------------------------------------------- markdown
_MARKDOWN = re.compile(r"[*_`#]+")


def strip_markdown(text: str) -> str:
    return _MARKDOWN.sub("", text)


# ---------------------------------------------------------------- вход модуля
def normalize(text: str, translit: str = "abbrev") -> str:
    """
    Полный слой одной функцией. Порядок шагов объяснён в шапке модуля и не произволен.

    `translit`: 'off' | 'abbrev' (по умолчанию) | 'full'. Выбор режима — свойство ДВИЖКА,
    а не текста: ESpeech получает 'full' (английских фонем в модели нет), Qwen — 'abbrev'
    (его английский владелец назвал лучшей частью, полная транслитерация его испортит).

    ⚠️ Транслитерация идёт ПОСЛЕ единиц: правило «°C» смотрит на латинскую «C», и если
    транслитерация отработает раньше, единица не развернётся.
    """
    text = strip_markdown(text)
    text = expand_code(text)
    text = expand_units(text)
    text = latin_to_cyrillic(text, translit)
    text = digits_to_words(text)
    return re.sub(r"\s{2,}", " ", text).strip()


