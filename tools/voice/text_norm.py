# -*- coding: utf-8 -*-
"""
Слой нормализации речи KLAS — общий для ЛЮБОГО движка синтеза.

Зачем отдельным модулем. Слой родился внутри `silero_daemon.py` (bugs/13: Silero молча ГЛОТАЛ
цифры), но он движку не принадлежит: espeak-ng у Piper и Qwen3-TTS одинаково не разворачивают
НАШИ сокращения — «11.4 ГБ» звучит как «одиннадцать четыре гб», «115 КБ/с» как «кб слэш с».
Владелец 2026-07-29, слушая макет Qwen: «единицы измерения плохо читает. Код тоже».
Значит слой переживает смену движка и обязан жить отдельно от него.

Импортировать модулем, а не из исполняемого скрипта: импорт `silero_daemon` запустил бы демона
целиком (EXP-0028).

Порядок применения важен и не произволен:
  1) markdown вон           — разметка не звучит
  2) код в слова            — ДО единиц: в коде есть «-m», «/», «=», которые единицы поняли бы неверно
  3) единицы в слова        — пока числа ещё ЦИФРАМИ (правила смотрят на цифру слева)
  4) дроби и числа в слова  — последним, иначе развернутые слова снова не с чем сопоставить

[NOT-TESTED] — маркер снимается после прогона на фикстуре и прослушивания.
"""
import re

# ---------------------------------------------------------------- числа
_ONES_M = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_ONES_F = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
         "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот"]


def _plural(n: int, forms):
    """forms = (1, 2-4, 5-0). Русская морфология числительных."""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def _under_1000(n: int, feminine: bool):
    out = []
    if n >= 100:
        out.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(_TEENS[n - 10])
        return out
    if n >= 20:
        out.append(_TENS[n // 10])
        n %= 10
    if n:
        out.append((_ONES_F if feminine else _ONES_M)[n])
    return out


def number_to_ru_words(num: int) -> str:
    if num == 0:
        return "ноль"
    parts = []
    if num < 0:
        parts.append("минус")
        num = -num
    for scale, (forms, fem) in (
        (10 ** 9, (("миллиард", "миллиарда", "миллиардов"), False)),
        (10 ** 6, (("миллион", "миллиона", "миллионов"), False)),
        (10 ** 3, (("тысяча", "тысячи", "тысяч"), True)),
    ):
        if num >= scale:
            chunk = num // scale
            parts += _under_1000(chunk, fem) + [_plural(chunk, forms)]
            num %= scale
    if num:
        parts += _under_1000(num, False)
    return " ".join(p for p in parts if p)


# Дробные: «11.4» и «11,4». Раньше их резало на два целых («одиннадцать четыре») —
# именно это владелец услышал в макете Qwen. Дробную часть читаем разрядом.
_FRACTION_NAMES = {1: ("десятая", "десятых"), 2: ("сотая", "сотых"), 3: ("тысячная", "тысячных")}


def _decimal_to_words(m) -> str:
    whole, frac = m.group(1), m.group(2)
    w = int(whole)
    f = int(frac)
    digits = len(frac)
    whole_words = " ".join(_under_1000(w, True)) if w else "ноль"
    whole_tail = _plural(w, ("целая", "целых", "целых"))
    if digits in _FRACTION_NAMES:
        one, many = _FRACTION_NAMES[digits]
        frac_tail = _plural(f, (one, many, many))
    else:                                    # разряд глубже тысячных не называем — читаем цифрами
        return f"{whole_words} {whole_tail} " + " ".join(_ONES_M[int(d)] or "ноль" for d in frac)
    frac_words = " ".join(_under_1000(f, True)) if f else "ноль"
    return f"{whole_words} {whole_tail} {frac_words} {frac_tail}"


_DECIMAL = re.compile(r"\b(\d+)[.,](\d+)\b")


def digits_to_words(text: str) -> str:
    """Дроби разворачиваем ПЕРВЫМИ, иначе целочисленное правило разрежет их пополам."""
    text = _DECIMAL.sub(_decimal_to_words, text)
    return re.sub(r"-?\d+", lambda m: number_to_ru_words(int(m.group())), text)


# ---------------------------------------------------------------- единицы
# Разворачиваем только то, что стоит ПОСЛЕ ЧИСЛА, — иначе «в» из «м/в» поедет на обычном тексте.
_UNIT_WORDS = [
    (r"°\s*C|℃|(?<=\d)\s*C\b", " градусов Цельсия"),
    (r"°\s*F|℉", " градусов Фаренгейта"),
    (r"%", " процентов"),
    (r"\bкб/с\b|\bКБ/с\b|\bkb/s\b", " килобайт в секунду"),
    (r"\bмб/с\b|\bМБ/с\b|\bmb/s\b", " мегабайт в секунду"),
    (r"\bгб/с\b|\bГБ/с\b|\bgb/s\b", " гигабайт в секунду"),
    (r"\bкм/ч\b", " километров в час"),
    (r"\bм/с\b", " метров в секунду"),
    (r"\bкб\b|\bКБ\b", " килобайт"),
    (r"\bмб\b|\bМБ\b", " мегабайт"),
    (r"\bгб\b|\bГБ\b", " гигабайт"),
    (r"\bтб\b|\bТБ\b", " терабайт"),
    (r"\bкм\b", " километров"),
    (r"\bсм\b", " сантиметров"),
    (r"\bмм\b", " миллиметров"),
    (r"\bкг\b", " килограммов"),
    (r"\bч\.", " часов"),
    (r"\bмин\b", " минут"),
    (r"\bсек\b", " секунд"),
    (r"\bт\.е\.", "то есть"),
    (r"\bт\.д\.", "так далее"),
    (r"\bт\.п\.", "тому подобное"),
]
_HAS_NUMBER_BEFORE = re.compile(r"\d\s*$")


def expand_units(text: str) -> str:
    for pattern, word in _UNIT_WORDS:
        def repl(m, word=word):
            before = text[:m.start()]
            return word if _HAS_NUMBER_BEFORE.search(before) or "." in m.group() or "%" in m.group() else m.group()
        text = re.sub(pattern, repl, text)
    return re.sub(r"\s{2,}", " ", text)


# ---------------------------------------------------------------- код
# Жалоба владельца «Код тоже». Цель НЕ в том, чтобы код можно было восстановить на слух, —
# цель в том, чтобы он ЗВУЧАЛ КАК РЕЧЬ, а не как набор символов. Поэтому разворачиваем
# математику и операторы, а кавычки просто снимаем: их содержимое произносится как текст.
_CODE_RULES = [
    (r"\bf\s*\(\s*x\s*\)", "эф от икс"),                 # частая форма записи функции
    (r"(?<=\s)-([a-zA-Z])\b", r"ключ \1"),               # флаг вида -m
    (r"--([a-zA-Z-]+)", r"ключ \1"),                     # длинный флаг
    (r"\s*==\s*", " равно равно "),
    (r"\s*=\s*", " равно "),
    (r"\s*\+\s*", " плюс "),
    (r"(?<=\d)\s*\*\s*(?=\d)", " умножить на "),
    (r"(?<=\d)\s*/\s*(?=\d)", " делить на "),
    (r"\s*->\s*", " стрелка "),
    (r"\s*=>\s*", " стрелка "),
    (r"[\"«»']", " "),                                    # кавычки не звучат — содержимое остаётся
    (r"\s*\|\s*", " вертикальная черта "),
    (r"\s*&&\s*", " и "),
]
# «2x» → «два икс»: без пробела синтез читает это одним комком
_IMPLICIT_MUL = re.compile(r"(?<=\d)(?=[a-zA-Zа-яА-Я])")


def expand_code(text: str) -> str:
    for pattern, repl in _CODE_RULES:
        text = re.sub(pattern, repl, text)
    text = _IMPLICIT_MUL.sub(" ", text)
    return re.sub(r"\s{2,}", " ", text)


# ---------------------------------------------------------------- markdown
_MARKDOWN = re.compile(r"[*_`#]+")


def strip_markdown(text: str) -> str:
    return _MARKDOWN.sub("", text)


# ---------------------------------------------------------------- вход модуля
def normalize(text: str) -> str:
    """Полный слой одной функцией. Порядок шагов объяснён в шапке модуля и не произволен."""
    text = strip_markdown(text)
    text = expand_code(text)
    text = expand_units(text)
    text = digits_to_words(text)
    return re.sub(r"\s{2,}", " ", text).strip()


if __name__ == "__main__":
    # Фикстура-самопроверка: слева вход, справа то, что НЕ ДОЛЖНО остаться в речи.
    # Инвариант из bugs/13 усилен: в речи не должно остаться ни одной ЦИФРЫ и ни одного
    # из сокращений, на которые жаловался владелец.
    CASES = [
        "Видеокарта RTX 5070 Ti заняла 11.4 ГБ из 16, температура 62 °C, скорость 115 КБ/с, до встречи осталось 15 минут.",
        'Выполните команду git commit -m "fix voice", затем npm run build. Функция f(x) = 2x при x от 1 до 5 вернёт 10.',
        "Загрузка 87%, осталось 2.5 мин.",
    ]
    bad = 0
    for c in CASES:
        out = normalize(c)
        print("ВХОД :", c)
        print("РЕЧЬ :", out)
        if re.search(r"\d", out):
            print("  ❌ в речи осталась цифра"); bad += 1
        if re.search(r"\b(ГБ|КБ|МБ)\b|°", out):
            print("  ❌ в речи осталось сокращение"); bad += 1
        print()
    print("ИТОГ:", "PASS" if bad == 0 else f"FAIL ({bad})")
