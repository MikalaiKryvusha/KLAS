// tools/voice/wake-chime.mjs — СИГНАЛЫ «СЛУШАЮ»: генератор и выслушка вариантов.
//
// Зачем. Владелец на живом тесте 2026-08-01: «звуковой сигнал активации имени сейчас неприятный,
// пик какой-то, нужны варианты приятных мягких сигналов. И после фразы ИИ нужно этот же сигнал
// подавать — то есть, когда 5 секунд слушания начинаются, чтобы я понимал, что опять могу говорить».
//
// Почему нынешний звук «пикает». Он был написан как СЛУЖЕБНЫЙ, а не как приглашение: синус 880 Гц,
// 0.15 с, атака 10 мс (`voice-wake.mjs`, ensureBeep). Резкий старт даёт щелчок-удар, высокая частота
// режет ухо, короткая длительность читается как «ошибка», а не как «говорите». Кандидаты ниже
// двигают ровно эти три ручки: ниже частота · медленная атака · тёплый обертон вместо голого синуса.
//
// ⚠️ СИГНАЛ ОБЯЗАН ОСТАВАТЬСЯ НЕРЕЧЕВЫМ. Он звучит в ту же комнату, где слушает активатор, и попадёт
// в микрофон. Замер `researches/23` §0: широкополосный шум детектору безразличен (0.986 на любом
// уровне), а РЕЧЬ ломает его наглухо. Поэтому здесь только тоны — никаких голосов, слов и хора.
//
// Собирается КОДОМ, а не хранится файлом: бинарник в git ради трети секунды синуса — лишняя
// сущность, а генератор И ЕСТЬ воспроизводимый исходник (то же основание, что у бипа).
//
// Запуск:
//   node tools/voice/wake-chime.mjs              ← собрать все варианты + склейку на выслушку
//   node tools/voice/wake-chime.mjs --play soft  ← послушать один (звук в комнате!)
//   node tools/voice/wake-chime.mjs --play all   ← послушать склейку подряд
//
// [NOT-TESTED] — судит ухо владельца, а не агент: «приятное» это перцептивный критерий (класс TASTE).

import { mkdirSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

const OUT = 'F:\\KLAS\\voice\\out\\chimes';
const SR = 16000;
const args = process.argv.slice(2);
const playArg = (() => { const i = args.indexOf('--play'); return i >= 0 ? args[i + 1] : null; })();

// Пиковая амплитуда ОДНА на все варианты: сравнивать надо тембр, а не громкость. Человек, слушая
// два звука разной громкости, сравнивает громкость — этот урок уже оплачен на выслушке голосов
// (`normalize-loudness.mjs`). 5000 из 32767 — заметно тише прежнего бипа (было 9000).
const PEAK = 5000;

/**
 * Один тон с мягкой огибающей.
 * @param {number} f      частота, Гц
 * @param {number} sec    длительность
 * @param {number} attack доля длительности на нарастание — ГЛАВНАЯ ручка «мягкости»:
 *                        резкий старт и есть тот самый «пик»
 * @param {number} amp    относительная амплитуда (0..1)
 * @param {number[]} partials обертоны как доли от основного тона: [1, 0.3] = основной + тихая октава
 */
/**
 * Тон КОЛОКОЛЬЧИКА: почти сразу звучит в полную силу и потом тает.
 *
 * ⚠️ Огибающая переделана по замечанию владельца 2026-08-01: «он нарастает, а нужно чтобы убывал».
 * Прежняя версия задавала атаку ДОЛЕЙ длительности (0.35 и больше), и звук набухал — это свелл, а
 * не колокольчик. Теперь атака — АБСОЛЮТНОЕ время в секундах и она короткая: её задача не «плавно
 * ввести», а лишь убрать щелчок в самом начале (щелчок и был исходным «пиком»). Всё остальное время
 * звук ЗАТУХАЕТ.
 *
 * @param {number} glide во сколько раз меняется высота К КОНЦУ звука: 1 — ровно, 0.75 — сползает
 *   вниз. Скольжением делается «нисходящий» сигнал БЕЗ второй ноты — владелец: «Не нужно две ноты пипи».
 */
function tone(f, sec, attackSec, amp, partials = [1], decaySoft = 1, glide = 1) {
  const n = Math.round(SR * sec);
  const out = new Float64Array(n);
  const aN = Math.max(1, Math.round(SR * attackSec));
  const norm = partials.reduce((a, b) => a + b, 0);
  let phase = 0;
  for (let i = 0; i < n; i++) {
    const t = i / n;
    const env = i < aN
      ? 0.5 * (1 - Math.cos((Math.PI * i) / aN))          // мягкий старт без щелчка
      : Math.exp((-3.4 / decaySoft) * ((i - aN) / (n - aN)));
    // Частота ведётся ФАЗОЙ, а не подстановкой в синус: подстановка при меняющейся частоте даёт
    // скачки фазы и слышимый треск. Накопление фазы — обычный способ сделать глиссандо чисто.
    const fi = f * (1 + (glide - 1) * t);
    phase += (2 * Math.PI * fi) / SR;
    let s = 0;
    for (let k = 0; k < partials.length; k++) s += partials[k] * Math.sin(phase * (k + 1));
    out[i] = (s / norm) * env * amp;
  }
  return out;
}

const silence = (sec) => new Float64Array(Math.round(SR * sec));

function concat(parts) {
  const n = parts.reduce((s, p) => s + p.length, 0);
  const out = new Float64Array(n);
  let o = 0;
  for (const p of parts) { out.set(p, o); o += p.length; }
  return out;
}

// Смешать наложением (для аккордов): длина по самому длинному.
function mix(parts) {
  const n = Math.max(...parts.map((p) => p.length));
  const out = new Float64Array(n);
  for (const p of parts) for (let i = 0; i < p.length; i++) out[i] += p[i];
  return out;
}

// ── Кандидаты ────────────────────────────────────────────────────────────────
// Ноты взяты из равномерного строя: A4=440. Интервалы выбраны «спокойные» — квинта и большая терция
// звучат как приглашение, а секунда или тритон тревожно.
// ⚠️ АТАКА ЗДЕСЬ В СЕКУНДАХ. Изначально она задавалась ДОЛЕЙ длительности, и при переделке
// огибающей (замечание владельца «нужно чтобы убывал») единица сменилась на секунды — а эти шесть
// вариантов остались со старыми числами. В итоге 0.35 читалось как 350 мс вместо 35%, и звуки
// зазвучали не так, как когда владелец их выбирал: «что-то сломалось, это не тот звук». Ошибки при
// этом не было ни одной — тихий дефект от смены единицы измерения. Числа ниже пересчитаны
// (доля × длительность) и снабжены исходной долей в комментарии, чтобы связь не потерялась.
const CANDIDATES = {
  // 1. Один мягкий тон пониже. Самое скромное изменение против нынешнего: та же идея, но без «пика».
  soft: () => tone(523.25, 0.34, 0.095, 1, [1, 0.25]),                      // было 0.28 доли

  // 2. Две ноты вверх — «слушаю». Восходящий ход человек читает как вопрос/приглашение.
  rise: () => concat([tone(440, 0.16, 0.048, 0.9, [1, 0.2]), tone(659.25, 0.3, 0.075, 1, [1, 0.2])]),

  // 3. Две ноты вниз — «готово». Нисходящий ход читается как завершение; здесь для сравнения.
  fall: () => concat([tone(659.25, 0.16, 0.048, 0.9, [1, 0.2]), tone(440, 0.3, 0.075, 1, [1, 0.2])]),

  // 4. Тёплый: основной тон и тихая квинта одновременно, длинный спад. Похоже на камертон.
  warm: () => mix([tone(392, 0.5, 0.175, 1, [1, 0.3, 0.1]), tone(587.33, 0.5, 0.2, 0.35, [1, 0.2])]),

  // 5. Стеклянный колокольчик: высокий, но с медленной атакой и длинным затуханием.
  glass: () => mix([tone(880, 0.55, 0.121, 0.8, [1, 0.15, 0.08]), tone(1318.5, 0.5, 0.15, 0.25)]),

  // 6. Совсем тихий выдох: низкий тон, очень мягкий, почти на грани слышимости.
  breath: () => tone(329.63, 0.45, 0.2, 0.85, [1, 0.4, 0.15]),

  // 7. ⭐ Тот самый `warm-low`, который выбрал владелец, — ДОСЛОВНО в прежнем виде (атака 0.35 доли
  //    = 210 мс). Оставлен в наборе намеренно: без эталона рядом невозможно услышать, что именно
  //    поменяли новые варианты.
  'warm-low': () => mix([tone(293.66, 0.6, 0.21, 1, [1, 0.25]), tone(440, 0.55, 0.22, 0.3, [1])]),
};

// ── Семейство «warm»: владелец выбрал его, но сказал «слишком острый» (2026-08-01) ──────────────
// Острота у исходного `warm` берётся из двух мест, и варианты двигают их по отдельности, чтобы было
// слышно, ЧТО именно её даёт:
//   · третья гармоника — 392 × 3 ≈ 1176 Гц, она и звенит;
//   · быстрый экспоненциальный спад — ухо читает его как удар, то есть перкуссию.
// Плюс третья ось — высота: чем ниже основной тон, тем меньше «шила» при той же громкости.
// Варианты описаны ДАННЫМИ, а не кодом, ради второго решения владельца (2026-08-01):
//   «Если я не говорю и слушание прекращается, нужно в таком же тоне но снисходящим тоном проиграть
//    звук — мне индикация, что слушание остановлено»
// То есть у каждого звука обязан быть близнец ТОГО ЖЕ ТЕМБРА, но нисходящий. Держать их двумя
// независимыми списками — верный способ, чтобы они разъехались: тембр правится в одном месте, а
// близнец остаётся старым. Поэтому спецификация одна, а строителя два.
// Основа — `warm-low`, выбранный владельцем («мне понравился warm-low»). Варианты двигают ровно то,
// что он забраковал: НАРАСТАНИЕ. Атака теперь в секундах и короткая, звук сразу звучит и тает.
const WARM_SPECS = {
  // 1. Он же, но колокольчиком: короткая атака, обычный спад.
  'bell': { lo: 293.66, hi: 440, sec: 0.7, attack: 0.02, partials: [1, 0.25], soft: 1, hiAmp: 0.3 },
  // 2. Длиннее хвост — тает дольше, звучит спокойнее.
  'bell-long': { lo: 293.66, hi: 440, sec: 1.1, attack: 0.02, partials: [1, 0.25], soft: 1.6, hiAmp: 0.3 },
  // 3. Атака чуть мягче (40 мс): проверяем, не слышен ли на 20 мс остаточный щелчок.
  'bell-soft': { lo: 293.66, hi: 440, sec: 0.8, attack: 0.045, partials: [1, 0.2], soft: 1.3, hiAmp: 0.28 },
  // 4. Чистые синусы без гармоник — самый гладкий тембр.
  'bell-pure': { lo: 293.66, hi: 440, sec: 0.9, attack: 0.03, partials: [1], soft: 1.4, hiAmp: 0.3 },
  // 5. Ещё ниже (ля большой октавы + ми): глубже и тише на слух.
  'bell-deep': { lo: 220, hi: 329.63, sec: 1.0, attack: 0.03, partials: [1, 0.22], soft: 1.5, hiAmp: 0.32 },
};

/** ОТКРЫТИЕ слушания: две ноты ОДНОВРЕМЕННО (аккорд, а не «пи-пи»), ровная высота, звук тает. */
const openChime = (s) => mix([
  tone(s.lo, s.sec, s.attack, 1, s.partials, s.soft),
  tone(s.hi, s.sec * 0.92, s.attack, s.hiAmp, [1], s.soft),
]);

/** ЗАКРЫТИЕ слушания: ТОТ ЖЕ аккорд, но высота плавно СПОЛЗАЕТ ВНИЗ по ходу звука.
 *
 *  ⚠️ Именно скольжением, а не второй нотой: владелец 2026-08-01 — «Не нужно две ноты пипи».
 *  Нисходящее движение человек читает как завершение, а общий тембр держит пару одной семьёй.
 *  Коэффициент 0.72 ≈ падение на большую терцию с небольшим запасом: слышно уверенно, но не воет. */
const closeChime = (s) => mix([
  tone(s.lo, s.sec * 1.05, s.attack, 1, s.partials, s.soft, 0.72),
  tone(s.hi, s.sec * 0.97, s.attack, s.hiAmp, [1], s.soft, 0.72),
]);

const WARM = Object.fromEntries(Object.entries(WARM_SPECS).flatMap(([n, s]) => [
  [n, () => openChime(s)],
  [`${n}-off`, () => closeChime(s)],
]));

function toWav(samples) {
  const pcm = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++) {
    pcm.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(samples[i] * PEAK))), i * 2);
  }
  const h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + pcm.length, 4); h.write('WAVE', 8);
  h.write('fmt ', 12); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22);
  h.writeUInt32LE(SR, 24); h.writeUInt32LE(SR * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34);
  h.write('data', 36); h.writeUInt32LE(pcm.length, 40);
  return Buffer.concat([h, pcm]);
}

const play = (file) => spawnSync('powershell', ['-NoProfile', '-Command',
  `(New-Object Media.SoundPlayer '${file}').PlaySync()`], { stdio: 'ignore' });

// ── Сборка ───────────────────────────────────────────────────────────────────
mkdirSync(OUT, { recursive: true });
// Семейство выбирается флагом: `--warm` собирает и склеивает ВАРИАНТЫ выбранного владельцем звука,
// чтобы на выслушке рядом стояли только сравнимые вещи, а не всё подряд.
const FAMILY = { ...CANDIDATES, ...WARM };
// В склейку идут ПАРАМИ: сразу за открывающим звуком его закрывающий близнец. Слушать их порознь
// бессмысленно — владелец выбирает не два звука, а одну семью, и важно, узнаётся ли родство на слух.
// ПЕРВЫМ в наборе `--warm` идёт ЭТАЛОН — тот самый `warm-low`, который владелец выбрал. Без него
// сравнивать не с чем: «этот лучше или хуже?» — вопрос, на который нельзя ответить в одиночку.
const names = args.includes('--warm') ? ['warm-low', ...Object.keys(WARM)] : Object.keys(CANDIDATES);

// Старые файлы убираются ПЕРЕД записью: иначе в каталоге лежат вперемешку звуки разных поколений,
// и «послушал не тот файл» становится вопросом везения.
for (const f of readdirSync(OUT)) if (f.endsWith('.wav')) rmSync(path.join(OUT, f), { force: true });

if (playArg && playArg !== 'all') {
  const f = path.join(OUT, `${playArg}.wav`);
  if (!FAMILY[playArg]) { console.error(`нет варианта «${playArg}». Есть: ${Object.keys(FAMILY).join(', ')}`); process.exit(1); }
  writeFileSync(f, toWav(FAMILY[playArg]()));
  console.log(`играю «${playArg}»`);
  play(f);
  process.exit(0);
}

for (const n of names) writeFileSync(path.join(OUT, `${n}.wav`), toWav(FAMILY[n]()));

// Склейка на выслушку: пауза 1.2 с между вариантами — достаточно, чтобы ухо отпустило предыдущий,
// и мало, чтобы не забыть его. Порядок печатается: без него склейка бесполезна.
const glued = concat(names.flatMap((n, i) => (i ? [silence(1.2), FAMILY[n]()] : [FAMILY[n]()])));
const allFile = path.join(OUT, args.includes('--warm') ? 'all-warm.wav' : 'all.wav');
writeFileSync(allFile, toWav(glued));

console.log(`Варианты сигнала «слушаю» — ${OUT}`);
names.forEach((n, i) => console.log(`  ${i + 1}. ${n}`));
console.log(`\nСклейка подряд: ${allFile}`);
console.log('Послушать:  node tools/voice/wake-chime.mjs --play all   (или --play <имя>)');

if (playArg === 'all') { console.log('\nиграю склейку'); play(allFile); }
